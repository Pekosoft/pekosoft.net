<div class="feature-row border">
  <svg class="standard-image-help"><use href="/icons.svg#release"></use></svg>
  <div class="justify">
    <h1>General</h1>
    Pekosoft Drum Machine is a four-voice, 16-step rhythm sequencer. Program kick, snare, hi-hat and percussion patterns, shape each voice and play the pattern through the shared meters.
  </div>
</div>

<div class="feature-row module">
  <svg class="standard-image-help"><use href="/icons.svg#tool"></use></svg>
  <div class="justify">
    <h1>Tool <span class="object">module</span></h1>
    The sequencer is split into steps 1-8 and 9-16. Each row controls one drum voice. Click or tap a step to cycle between off, normal and accent velocity. Drag across steps to paint the selected velocity.
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help"><use href="/icons.svg#sound"></use></svg>
  <div class="justify">
    <h1>Voice <span class="object">buttons</span></h1>
    KICK, SNARE, HI-HAT and PERC audition and select the corresponding voice. Number keys 1-4 provide the same audition shortcuts.
  </div>
</div>

<div class="feature-row border">
  <svg class="standard-image-help"><use href="/icons.svg#sound"></use></svg>
  <div class="justify">
    <h1>Mute <span class="object">buttons</span></h1>
    Toggle playback mute for each voice. Muted steps stay visible and remain in saved pattern data. <span class="default">Default: all voices audible.</span>
  </div>
</div>

